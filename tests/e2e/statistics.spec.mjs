import { test, expect, takeTicket, cancelTicket, walkIn, callNext, mutation, addService } from './fixtures.mjs';

test('issued outcomes, rates and per-round counts follow served, cancelled and dropped Tickets', async ({ page, shop: fixture, actor }) => {
  const first = await actor();
  const second = await actor();
  const third = await actor();
  const fourth = await actor();
  const completed = await takeTicket(first.page, fixture.shop, fixture.service);
  await takeTicket(second.page, fixture.shop, fixture.service);
  await takeTicket(third.page, fixture.shop, fixture.service);
  await takeTicket(fourth.page, fixture.shop, fixture.service);
  await cancelTicket(fourth.page);
  const called = await callNext(page, fixture.service);
  expect(called.id).toBe(completed.ticket.id);
  await mutation(page, `/api/tickets/${called.id}/start`, () => page.getByRole('button', { name: 'Start service', exact: true }).click());
  await mutation(page, `/api/tickets/${called.id}/complete`, () => page.getByRole('button', { name: 'Complete', exact: true }).click());
  const skipped = await callNext(page, fixture.service);
  await mutation(page, `/api/tickets/${skipped.id}/skip`, () => page.getByRole('button', { name: 'Skip', exact: true }).click());
  await page.getByRole('button', { name: 'Close now', exact: true }).click();
  await mutation(page, `/api/queues/${fixture.service.queue.id}/drop`, () => page.getByRole('dialog').getByRole('button', { name: 'Close the Queue now', exact: true }).click());
  await expect(third.page.getByRole('heading', { name: 'Shop closed this Queue', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Statistics', exact: true }).click();
  await expect(page.locator('.stats-hero-number')).toHaveText('4');
  const row = name => page.locator('.stats-rows').first().locator('.stats-row').filter({ has: page.locator('dt').filter({ hasText: new RegExp('^' + name) }) });
  await expect(row('Completed').locator('.stats-value')).toHaveText('1');
  await expect(row('Skipped').locator('.stats-value')).toHaveText('25');
  await expect(row('Cancelled').locator('.stats-value')).toHaveText('25');
  await expect(row('Shop closed').locator('.stats-value')).toHaveText('1');
  await expect(page.locator('.stats-note')).toContainText('4 finished Tickets');
  await page.getByText('Ticket counts by Business day', { exact: true }).click();
  await expect(page.locator('.demand-values').first().locator('.stats-value')).toHaveText('4');
  await expect(page.locator('.demand-cell')).toHaveCount(168);
});

test('Service and Business-day filters keep reopened rounds separate while combining Customer and Walk-in demand', async ({ page, shop: fixture, actor }) => {
  const customer = await actor();
  await takeTicket(customer.page, fixture.shop, fixture.service);
  await cancelTicket(customer.page);
  await page.getByRole('button', { name: 'Stop accepting', exact: true }).click();
  await expect(page.locator('.close-status')).toHaveText('Business day closed');
  await page.getByRole('link', { name: 'Shop', exact: true }).click();
  await mutation(page, `/api/queues/${fixture.service.queue.id}/open`, () => page.locator('.service-item').filter({ hasText: fixture.service.name }).getByRole('button', { name: 'Open Queue', exact: true }).click());
  const wash = await addService(page, fixture.shop, { name: 'Wash', prefix: 'W' });
  await page.goto('/owner/queue');
  await expect(page.locator('.live-label')).toHaveText('Live');
  await walkIn(page, fixture.service);
  await walkIn(page, wash);
  await page.getByRole('link', { name: 'Statistics', exact: true }).click();
  await expect(page.locator('.stats-hero-number')).toHaveText('3');
  await page.getByRole('tab', { name: 'Latest round', exact: true }).click();
  await expect(page.locator('.stats-hero-number')).toHaveText('2');
  await page.getByRole('combobox', { name: 'Service', exact: true }).selectOption(fixture.service.id);
  await expect(page.locator('.stats-hero-number')).toHaveText('1');
  await page.getByRole('tab', { name: '7 rounds', exact: true }).click();
  await expect(page.locator('.stats-hero-number')).toHaveText('2');
  await page.getByText('Ticket counts by Business day', { exact: true }).click();
  await expect(page.locator('.demand-values').first().locator('.stats-value')).toHaveText(['1', '1']);
  await page.getByRole('combobox', { name: 'Service', exact: true }).selectOption(wash.id);
  await expect(page.locator('.stats-hero-number')).toHaveText('1');
  await expect(page.locator('.stats-note')).toContainText('1 Tickets are still open');
  await expect(page.locator('.demand-section')).toContainText('Asia/Bangkok');
});
